import test from 'node:test';
import assert from 'node:assert/strict';
import {EXAMPLE,modelFromStep,derivePI,evaluateMotor,arduinoSketch} from '../modules/my-system/model.js';
test('step test derives measured K from RPM and PWM',()=>{
 const m=modelFromStep({pwmPercent:50, finalRpm:300, tauSeconds:.08});
 assert.ok(Math.abs(m.K-2*Math.PI/10)<1e-10); assert.equal(m.tau,.08);
});
test('invalid step measurements are rejected',()=>assert.throws(()=>modelFromStep({pwmPercent:0,finalRpm:300,tauSeconds:.1}),RangeError));
test('PI pole placement reconstructs target damping',()=>{
 const g=derivePI({K:EXAMPLE.K,tau:.06,desiredZeta:.75,desiredWn:25});
 const r=evaluateMotor({K:EXAMPLE.K,tau:.06,...g,target:30});
 assert.ok(Math.abs(r.predicted.zeta-.75)<1e-10);
});
test('P1 motor preset has damping in practical band and requires less than 100 percent PWM',()=>{
 const r=evaluateMotor(EXAMPLE);
 assert.equal(r.dampingTarget,true);assert.equal(r.achievable,true);assert.ok(r.requiredPWM>50&&r.requiredPWM<60);
 assert.ok(r.peakPWM<=100+1e-9);assert.ok(r.metrics.settled);
});
test('unreachable speed target is flagged',()=>assert.equal(evaluateMotor({...EXAMPLE,target:100}).achievable,false));
test('Arduino code is generated by P3 and retains hardware placeholders',()=>{
 const s=arduinoSketch({Kp:2,Ki:60,Kd:0,target:30});
 assert.match(s,/readPlantOutput\(\)/);assert.match(s,/TODO/);assert.match(s,/Kp = 2.0f/);
});
